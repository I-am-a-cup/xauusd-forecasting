# Воспроизводимая выгрузка исходных котировок XAU/USD.
# Запускать из корня репозитория. Последняя дата — исключающая граница.
# Наличие -v позволяет сохранить объём и отфильтровать пустые свечи.
# Внимание: UTC-календарные свечи ещё не эквивалентны торговым сессиям.
npx --yes dukascopy-node@1.51.1 -i xauusd -from 2025-10-28 -to 2026-10-28 -t d1 -p bid -v -f csv -utc 0 -dir data/raw
if ($LASTEXITCODE -ne 0) {
    throw "Не удалось выгрузить данные Dukascopy."
}
